# Ввод двух различных вещественных чисел
number1 = float(input("Введите первое число: "))
number2 = float(input("Введите второе число: "))

print(f"\nИсходные числа: {number1} и {number2}")
print("-" * 50)

# ------------------------------------------------------------
# а) Два неполных условных оператора
# ------------------------------------------------------------
print("а) Используя два неполных условных оператора:")

max_number_a = number1  # предполагаем, что первое число - наибольшее

# Если второе число больше первого, то обновляем максимум
if number2 > number1:
    max_number_a = number2

# Если числа равны (хотя по условию они различны, но на всякий случай)
if number1 > number2:
    max_number_a = number1

print(f"   Наибольшее число: {max_number_a}")

print("-" * 50)

# ------------------------------------------------------------
# б) Один неполный условный оператор
# ------------------------------------------------------------
print("б) Используя один неполный условный оператор:")

max_number_b = number1  # предполагаем, что первое число - наибольшее

# Только если второе число больше первого, меняем значение
if number2 > number1:
    max_number_b = number2

print(f"   Наибольшее число: {max_number_b}")

print("-" * 50)

# Проверка (для себя, не влияет на решение)
print("Проверка с помощью встроенной функции max():", max(number1, number2))
